// Runs at deploy time: embeds the frontend HTML pages into a module the Netlify Server bundles.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pages = ['jay-ganesh-invoice-pro.html', 'dreampay-website.html']
const out = Object.fromEntries(pages.map((name) => [name, fs.readFileSync(path.join(root, 'frontend', name), 'utf8')]))
fs.writeFileSync(
  path.join(root, 'netlify', 'server', 'pages.generated.mjs'),
  `// Generated by scripts/embed-frontend.mjs. Do not edit.\nexport default ${JSON.stringify(out)}\n`,
)
console.log(`Embedded ${pages.length} frontend pages into the Netlify Server bundle`)
